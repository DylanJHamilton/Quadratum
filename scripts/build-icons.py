"""Generate bounded Liquid icon banks from the versioned SVG library.
Only the requested icon markup is emitted; no sprite download or JS is required.
"""
from pathlib import Path
import re, collections
root = Path(__file__).resolve().parents[1]
groups = collections.defaultdict(list)
for name, body in re.findall(r'<symbol\b[^>]*id="([^"]+)"[^>]*>(.*?)</symbol>', (root/'assets/icons.svg').read_text(encoding='utf-8'), re.S):
    stem = re.sub(r'^(lucide|tabler)-', '', name)
    key = stem[0] + str(len(stem) % 4)
    groups[key].append((name, body))
lines = ["{%- comment -%}Generated by scripts/build-icons.py. Render one icon without a network sprite.{%- endcomment -%}", "{%- assign icon_stem = symbol_id | remove_first: 'lucide-' | remove_first: 'tabler-' -%}", "{%- assign icon_bucket = icon_stem.size | modulo: 4 -%}", "{%- assign icon_key = icon_stem | slice: 0 | append: icon_bucket -%}", "{%- case icon_key -%}"]
for key, symbols in sorted(groups.items()):
    name = 'q-icon-bank-' + key
    lines.append("{%- when '" + key + "' -%}{%- render '" + name + "', symbol_id: symbol_id -%}")
    text = "{%- comment -%}Generated icon bank; edit the source SVG, then run scripts/build-icons.py.{%- endcomment -%}\n{%- case symbol_id -%}\n"
    text += '\n'.join("{%- when '" + name + "' -%}" + body for name,body in symbols)
    text += '\n{%- endcase -%}\n'
    assert len(text.encode()) < 200000, key
    (root/'snippets'/f'{name}.liquid').write_text(text, encoding='utf-8')
lines.append('{%- endcase -%}')
(root/'snippets/q-icon-symbol.liquid').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'Generated {len(groups)} banks for {sum(map(len,groups.values()))} icons')
